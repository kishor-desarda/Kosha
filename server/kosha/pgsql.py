# ------------------------------------------------------------------------------------------- tokens --

_TOKEN = re.compile(r"""
    (?P<ws>\s+)
  | (?P<comment>--[^\n]*|/\*.*?\*/)
  | (?P<string>'(?:[^']|'')*')
  | (?P<qident>"(?:[^"]|"")*"|`(?:[^`]|``)*`)
  | (?P<param>\?\d*|:[A-Za-z_][A-Za-z0-9_]*)
  | (?P<number>(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?)
  | (?P<word>[A-Za-z_][A-Za-z0-9_$]*)
  | (?P<op>::|\|\||==|!=|<>|<=|>=|<<|>>|[(),;.=<>+\-*/%&|~])
  | (?P<other>.)
""", re.S | re.X)


@dataclass
class Tok:
    kind: str     # string qident param number word op other raw
    text: str

    @property
    def up(self) -> str:
        return self.text.upper() if self.kind == "word" else ""

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"Tok({self.kind},{self.text!r})"


class Group(list):
    """Items between a "(" and its ")"."""


def _raw(text: str) -> Tok:
    """SQL written by the translator itself: emitted as is (place holders and %% already final)."""
    return Tok("raw", text)


def _w(text: str) -> Tok:
    return Tok("word", text)


def _op(text: str) -> Tok:
    return Tok("op", text)


def tokenize(sql: str) -> list[Tok]:
    out = []
    for m in _TOKEN.finditer(sql):
        kind = m.lastgroup
        if kind in ("ws", "comment"):
            continue
        text = m.group()
        if kind == "qident" and text.startswith("`"):
            text = '"' + text[1:-1].replace("``", "`").replace('"', '""') + '"'
        out.append(Tok(kind, text))
    return out


def _tree(tokens: list[Tok]) -> Group:
    root = Group()
    stack = [root]
    for t in tokens:
        if t.kind == "op" and t.text == "(":
            g = Group()
            stack[-1].append(g)
            stack.append(g)
        elif t.kind == "op" and t.text == ")":
            if len(stack) == 1:
                raise ValueError("unbalanced brackets in SQL")
            stack.pop()
        else:
            stack[-1].append(t)
    if len(stack) != 1:
        raise ValueError("unbalanced brackets in SQL")
    return root


def _render(items: Iterable, out: list[str] | None = None) -> list[str]:
    out = [] if out is None else out
    for it in items:
        if isinstance(it, Group):
            out.append("(")
            _render(it, out)
            out.append(")")
        elif it.kind == "param":
            out.append("%s" if it.text.startswith("?") else f"%({it.text[1:]})s")
        elif it.kind == "raw":
            out.append(it.text)
        else:
            out.append(it.text.replace("%", "%%"))
    return out


_NO_SPACE_BEFORE = {")", ",", ".", "::", ";"}
_NO_SPACE_AFTER = {"(", ".", "::"}


def render(items: Iterable) -> str:
    parts = _render(items)
    s = []
    prev = ""
    for p in parts:
        if s and p not in _NO_SPACE_BEFORE and not p.startswith("::") and prev not in _NO_SPACE_AFTER \
                and not (p == "(" and _is_name(prev)):
            s.append(" ")
        s.append(p)
        prev = p
    return "".join(s)


def _is_name(text: str) -> bool:
    return bool(re.fullmatch(r"[A-Za-z_][A-Za-z0-9_$]*", text))


def _is(it, *words: str) -> bool:
    return isinstance(it, Tok) and it.kind == "word" and it.text.upper() in words


def _is_op(it, *ops: str) -> bool:
    return isinstance(it, Tok) and it.kind == "op" and it.text in ops


def _split_commas(items: list) -> list[list]:
    parts: list[list] = [[]]
    for it in items:
        if _is_op(it, ","):
            parts.append([])
        else:
            parts[-1].append(it)
    return parts


def _join_commas(parts: list[list]) -> list:
    out: list = []
    for k, p in enumerate(parts):
        if k:
            out.append(_op(","))
        out.extend(p)
    return out


def _ident_name(it) -> str:
    """Plain name of an identifier token as PostgreSQL stores it."""
    if it.kind == "qident":
        return it.text[1:-1].replace('""', '"')
    return it.text.lower()


def _quote(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def _str(value: str) -> Tok:
    return Tok("string", "'" + value.replace("'", "''") + "'")


# ------------------------------------------------------------------------------------- the result --

@dataclass(frozen=True)
class Translated:
    sql: str                         # for psycopg: %s place holders, literal % doubled
    action: str = ""                 # "begin" | "commit" | "rollback" | "noop" | ""
    write: bool = False              # changes data or schema (takes the write lock)
    ddl: bool = False                # changes the schema
    insert_table: str = ""           # INSERT target (for RETURNING id and upserts)
    insert_columns: tuple = ()
    returning: bool = False          # the statement has its own RETURNING
    upsert: bool = False             # INSERT OR REPLACE: UPSERT_MARK must be replaced by a conflict clause


UPSERT_MARK = "/*kosha:upsert*/"

_WRITE_WORDS = {"INSERT", "UPDATE", "DELETE", "REPLACE", "CREATE", "ALTER", "DROP", "TRUNCATE", "GRANT", "REVOKE",
                "COMMENT", "REINDEX"}
_DDL_WORDS = {"CREATE", "ALTER", "DROP", "TRUNCATE", "COMMENT", "REINDEX"}
_CLAUSE_END = {"LIMIT", "OFFSET", "FETCH", "FOR", "UNION", "INTERSECT", "EXCEPT", "RETURNING", "WINDOW", "ON"}
_CONSTRAINT_WORDS = {"CONSTRAINT", "PRIMARY", "NOT", "NULL", "UNIQUE", "CHECK", "DEFAULT", "COLLATE", "REFERENCES",
                     "GENERATED", "AS"}
_TABLE_CONSTRAINT_WORDS = {"CONSTRAINT", "PRIMARY", "UNIQUE", "CHECK", "FOREIGN"}


@functools.lru_cache(maxsize=4096)
def translate(sql: str) -> Translated:
    """Translate one SQLite statement for PostgreSQL. Raises ValueError for what cannot be translated."""
    tokens = tokenize(sql)
    while tokens and _is_op(tokens[-1], ";"):
        tokens.pop()
    if not tokens:
        return Translated("", action="noop")
    if any(_is_op(t, ";") for t in tokens):
        raise ValueError("one statement at a time (use executescript for several)")
    if any(t.kind == "param" and len(t.text) > 1 and t.text[1].isdigit() for t in tokens):
        raise ValueError("numbered place holders (?1, ?2) are not supported; use ?")
    first = tokens[0].up
    if first in ("BEGIN", "COMMIT", "END", "ROLLBACK") and not (first == "ROLLBACK" and any(_is(t, "TO") for t in tokens)):
        return Translated("", action={"BEGIN": "begin", "COMMIT": "commit", "END": "commit"}.get(first, "rollback"))
    if first == "PRAGMA":
        return _pragma(tokens)
    if first in ("VACUUM", "ANALYZE"):
        return Translated("", action="noop")
    if first == "CREATE" and any(_is(t, "TRIGGER", "VIRTUAL") for t in tokens[1:4]):
        raise ValueError("SQLite triggers and virtual tables are not translated; give the database change a "
                         "SQL_POSTGRESQL version")

    words = {t.up for t in tokens if t.kind == "word"}
    write = first in _WRITE_WORDS or (first == "WITH" and bool(words & {"INSERT", "UPDATE", "DELETE"})) \
        or ("FOR" in words and "UPDATE" in words)
    ddl = first in _DDL_WORDS
    tree = _tree(tokens)

    insert_table, insert_cols, upsert, ignore = "", (), False, False
    if first in ("INSERT", "REPLACE"):
        tree, insert_table, insert_cols, upsert, ignore = _insert_head(tree)
    returning = any(_is(t, "RETURNING") for t in tree)

    if first == "CREATE" and _create_table_body(tree) is not None:
        _ddl_create_table(tree)
    elif first == "ALTER":
        _ddl_alter_table(tree)

    tree = _level(tree)

    if ignore or upsert:
        tail = [_raw(" ON CONFLICT DO NOTHING" if ignore else UPSERT_MARK)]
        pos = next((k for k, t in enumerate(tree) if _is(t, "RETURNING")), len(tree))
        tree[pos:pos] = tail
    return Translated(render(tree), write=write or ddl, ddl=ddl, insert_table=insert_table,
                      insert_columns=insert_cols, returning=returning, upsert=upsert)


def split_statements(script: str) -> list[str]:
    """Split a script at top-level semicolons (strings and comments respected)."""
    out, start = [], 0
    for m in _TOKEN.finditer(script):
        if m.lastgroup == "op" and m.group() == ";":
            stmt = script[start:m.start()].strip()
            if stmt and tokenize(stmt):
                out.append(stmt)
            start = m.end()
    stmt = script[start:].strip()
    if stmt and tokenize(stmt):
        out.append(stmt)
    return out


# ------------------------------------------------------------------------------------ statements --

def _insert_head(tree: Group):
    """INSERT OR IGNORE / OR REPLACE / REPLACE INTO -> plain INSERT; returns table, columns and flags."""
    items = list(tree)
    upsert = ignore = False
    if _is(items[0], "REPLACE"):
        items[0] = _w("INSERT")
        upsert = True
    elif len(items) > 2 and _is(items[1], "OR"):
        how = items[2].up
        del items[1:3]
        upsert, ignore = how == "REPLACE", how == "IGNORE"
    if len(items) < 2 or not _is(items[1], "INTO"):
        items.insert(1, _w("INTO"))
    k = 2
    if k + 2 < len(items) and _is(items[k], "MAIN", "TEMP") and _is_op(items[k + 1], "."):
        del items[k:k + 2]                   # SQLite's schema names
    elif k + 2 < len(items) and _is_op(items[k + 1], "."):
        k += 2                               # a PostgreSQL schema name stays
    name = items[k] if k < len(items) else None
    table = _ident_name(name) if isinstance(name, Tok) else ""
    cols: tuple = ()
    j = k + 1
    if j < len(items) and _is(items[j], "AS"):
        j += 2
    if j < len(items) and isinstance(items[j], Group):
        cols = tuple(_ident_name(p[0]) for p in _split_commas(list(items[j])) if p and isinstance(p[0], Tok))
    return Group(items), table, cols, upsert, ignore


def _pragma(tokens: list[Tok]) -> Translated:
    rest = tokens[1:]
    if len(rest) >= 2 and _is_op(rest[1], "."):
        rest = rest[2:]
    name = rest[0].up if rest else ""
    if len(rest) >= 2 and _is_op(rest[1], "="):
        return Translated("", action="noop")   # settings: journal_mode, synchronous ... PostgreSQL has its own
    arg = ""
    if len(rest) >= 2 and isinstance(rest[1], Tok) and rest[1].text == "(" and len(rest) > 2:
        a = rest[2]           # a quoted name is matched exactly, a bare one case-insensitively (as SQLite does)
        arg = _quote(a.text[1:-1].replace("''", "'")) if a.kind == "string" else a.text if a.kind == "qident" \
            else a.text.lower()
    lit = "'" + arg.replace("'", "''") + "'"
    if name in ("TABLE_INFO", "TABLE_XINFO"):
        return Translated(
            "SELECT (row_number() OVER (ORDER BY a.attnum) - 1)::int AS cid, a.attname::text AS name, "
            "upper(format_type(a.atttypid, a.atttypmod)) AS type, a.attnotnull::int AS notnull, "
            "pg_get_expr(d.adbin, d.adrelid) AS dflt_value, "
            "COALESCE((SELECT k.o FROM unnest(p.indkey::int2[]) WITH ORDINALITY k(n, o) WHERE k.n = a.attnum), 0)::int "
            "AS pk "
            "FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum "
            "LEFT JOIN pg_index p ON p.indrelid = a.attrelid AND p.indisprimary "
            f"WHERE a.attrelid = to_regclass({lit}) AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum")
    if name == "INDEX_LIST":
        return Translated(
            "SELECT (row_number() OVER (ORDER BY c.relname) - 1)::int AS seq, c.relname::text AS name, "
            "i.indisunique::int AS \"unique\", CASE WHEN i.indisprimary THEN 'pk' ELSE 'c' END AS origin, "
            "(i.indpred IS NOT NULL)::int AS partial FROM pg_index i JOIN pg_class c ON c.oid = i.indexrelid "
            f"WHERE i.indrelid = to_regclass({lit}) ORDER BY c.relname")
    if name in ("INTEGRITY_CHECK", "QUICK_CHECK"):
        return Translated("SELECT 'ok' AS integrity_check")
    if name == "FOREIGN_KEYS":
        return Translated("SELECT 1 AS foreign_keys")
    if name in ("FOREIGN_KEY_CHECK",):
        return Translated("SELECT 1 WHERE false")
    return Translated("", action="noop")   # journal_mode, synchronous, busy_timeout ... PostgreSQL handles these


# ------------------------------------------------------------------------------------------- DDL --

def _create_table_body(tree: Group) -> int | None:
    """Index of the column-list group of CREATE [TEMP] TABLE [IF NOT EXISTS] name (...)."""
    k = 1
    while k < len(tree) and _is(tree[k], "TEMP", "TEMPORARY", "UNLOGGED"):
        k += 1
    if not (k < len(tree) and _is(tree[k], "TABLE")):
        return None
    k += 1
    if k + 2 < len(tree) and _is(tree[k], "IF") and _is(tree[k + 1], "NOT") and _is(tree[k + 2], "EXISTS"):
        k += 3
    k += 1                                   # the name
    if k + 1 < len(tree) and _is_op(tree[k], "."):
        k += 2
    if k < len(tree) and isinstance(tree[k], Group):
        return k
    return None


def _ddl_create_table(tree: Group) -> None:
    k = _create_table_body(tree)
    body = tree[k]
    parts = _split_commas(list(body))
    new = []
    for p in parts:
        if p and _is(p[0], *_TABLE_CONSTRAINT_WORDS):
            new.append(_strip_on_conflict(p))
        else:
            new.append(_column_def(p))
    tree[k] = Group(_join_commas(new))
    # table options SQLite has and PostgreSQL does not
    tail = tree[k + 1:]
    keep = []
    i = 0
    while i < len(tail):
        if _is(tail[i], "WITHOUT") and i + 1 < len(tail) and _is(tail[i + 1], "ROWID"):
            i += 2
        elif _is(tail[i], "STRICT") or _is_op(tail[i], ","):
            i += 1
        else:
            keep.append(tail[i])
            i += 1
    del tree[k + 1:]
    tree.extend(keep)


def _ddl_alter_table(tree: Group) -> None:
    for k, it in enumerate(tree):
        if _is(it, "ADD"):
            j = k + 1
            if j < len(tree) and _is(tree[j], "COLUMN"):
                j += 1
            if j < len(tree) and _is(tree[j], *_TABLE_CONSTRAINT_WORDS):
                return
            coldef = _column_def(list(tree[j:]))
            del tree[j:]
            tree.extend(coldef)
            return


def _strip_on_conflict(items: list) -> list:
    out, i = [], 0
    while i < len(items):
        if _is(items[i], "ON") and i + 2 < len(items) and _is(items[i + 1], "CONFLICT"):
            i += 3
            continue
        out.append(items[i])
        i += 1
    return out


def _sqlite_type(type_items: list) -> list:
    """SQLite type name -> PostgreSQL type that stores the same values (SQLite's affinity rules)."""
    if not type_items:
        return [_w("TEXT")]
    name = " ".join(t.text.upper() for t in type_items if isinstance(t, Tok))
    if "INT" in name:
        return [_w("BIGINT")]
    if any(s in name for s in ("CHAR", "CLOB", "TEXT", "JSON", "DATE", "TIME", "UUID")):
        return [_w("TEXT")]
    if "BLOB" in name or "BYTEA" in name:
        return [_w("BYTEA")]
    if any(s in name for s in ("REAL", "FLOA", "DOUB")):
        return [_w("DOUBLE"), _w("PRECISION")]
    if "BOOL" in name:
        return [_w("BIGINT")]
    if name.startswith(("NUMERIC", "DECIMAL")):
        return type_items
    return [_w("TEXT")]


def _column_def(items: list) -> list:
    if not items:
        return items
    name, rest = items[0], items[1:]
    k = 0
    while k < len(rest) and not _is(rest[k], *_CONSTRAINT_WORDS):
        k += 1
    type_items, cons = rest[:k], rest[k:]
    is_integer = len(type_items) == 1 and _is(type_items[0], "INTEGER")
    collate: list = []
    out: list = []
    pk = False
    i = 0
    while i < len(cons):
        it = cons[i]
        if _is(it, "COLLATE") and i + 1 < len(cons):
            collate = [_w("COLLATE"), _collation(cons[i + 1])]
            i += 2
            continue
        if _is(it, "AUTOINCREMENT"):
            i += 1
            continue
        if _is(it, "ON") and i + 1 < len(cons) and _is(cons[i + 1], "CONFLICT"):
            i += 3
            continue
        if _is(it, "PRIMARY") and i + 1 < len(cons) and _is(cons[i + 1], "KEY"):
            pk = True
            out += [it, cons[i + 1]]
            i += 2
            if i < len(cons) and _is(cons[i], "ASC", "DESC"):
                i += 1
            continue
        if _is(it, "DEFAULT") and i + 1 < len(cons) and _is(cons[i + 1], "CURRENT_TIMESTAMP", "CURRENT_DATE",
                                                            "CURRENT_TIME"):
            out += [it, Group([_raw(_now_expr(cons[i + 1].up))])]
            i += 2
            continue
        out.append(it)
        i += 1
    if pk and is_integer:
        new_type = [_w("BIGINT"), _w("GENERATED"), _w("BY"), _w("DEFAULT"), _w("AS"), _w("IDENTITY")]
    else:
        new_type = _sqlite_type(type_items)
    return [name, *new_type, *collate, *out]


def _collation(tok) -> Tok:
    up = tok.text.upper().strip('"')
    if up == "NOCASE":
        return _w("nocase")
    if up == "BINARY":
        return Tok("qident", '"C"')
    if up == "RTRIM":
        raise ValueError("COLLATE RTRIM is not available on PostgreSQL")
    return tok


# ---------------------------------------------------------------------------- expressions, clauses --

_NOW_FORMAT = {"CURRENT_TIMESTAMP": "YYYY-MM-DD HH24:MI:SS", "CURRENT_DATE": "YYYY-MM-DD", "CURRENT_TIME": "HH24:MI:SS"}


def _now_expr(word: str) -> str:
    return f"to_char(timezone('UTC', now()), '{_NOW_FORMAT[word]}')"


_MODIFIER = re.compile(r"^\s*([+-]?\d+(?:\.\d+)?)\s+(second|minute|hour|day|month|year)s?\s*$", re.I)
_STRFTIME = {"%Y": "YYYY", "%m": "MM", "%d": "DD", "%H": "HH24", "%M": "MI", "%S": "SS", "%j": "DDD",
             "%f": "SS.MS", "%W": "WW", "%%": "%%"}


def _time_value(args: list[list]) -> str:
    """SQLite time value + modifiers -> a PostgreSQL timestamp (UTC, without time zone)."""
    if not args or not args[0]:
        base = "timezone('UTC', now())"
    else:
        a = args[0]
        if len(a) == 1 and a[0].kind == "string" and a[0].text.lower() == "'now'":
            base = "timezone('UTC', now())"
        else:
            base = f"timezone('UTC', ({render(a)})::timestamptz)"
    for m in args[1:]:
        if len(m) != 1 or m[0].kind != "string":
            raise ValueError("date modifiers must be written as text, for example '-7 days'")
        text = m[0].text[1:-1]
        mm = _MODIFIER.match(text)
        if mm:
            base = f"({base} + interval '{mm.group(1)} {mm.group(2).lower()}s')"
        elif text.lower() in ("utc", "localtime"):
            continue
        elif text.lower() == "start of day":
            base = f"date_trunc('day', {base})"
        elif text.lower() == "start of month":
            base = f"date_trunc('month', {base})"
        elif text.lower() == "start of year":
            base = f"date_trunc('year', {base})"
        else:
            raise ValueError(f"the date modifier {text!r} is not translated for PostgreSQL")
    return base


def _function(name: str, args: list[list], group: Group) -> list | None:
    """Rewrite one SQLite function call; None leaves it as it is."""
    n = len(args) if any(args) else 0
    if name == "IFNULL":
        return [_w("COALESCE"), group]
    if name == "LAST_INSERT_ROWID" and n == 0:
        return [_w("lastval"), Group()]
    if name == "IIF" and n == 3:
        return [_w("CASE"), _w("WHEN"), *args[0], _w("THEN"), *args[1], _w("ELSE"), *args[2], _w("END")]
    if name == "INSTR" and n == 2:
        return [_w("strpos"), Group([Group(args[0]), _raw("::text COLLATE \"default\""), _op(","), *args[1]])]
    if name == "REPLACE" and n == 3:
        return [_w("replace"), Group([Group(args[0]), _raw("::text COLLATE \"default\""), _op(","), *args[1], _op(","),
                                      *args[2]])]
    if name == "GROUP_CONCAT" and n in (1, 2):
        first = list(args[0])
        distinct = []
        if first and _is(first[0], "DISTINCT"):
            distinct, first = [first[0]], first[1:]
        sep = args[1] if n == 2 else [_str(",")]
        return [_w("string_agg"), Group([*distinct, Group(first), _raw("::text"), _op(","), *sep])]
    if name in ("MAX", "MIN") and n >= 2:
        return [_w("GREATEST" if name == "MAX" else "LEAST"), group]
    if name == "ROUND" and n == 2:
        return [_w("ROUND"), Group([Group(args[0]), _raw("::numeric"), _op(","), *args[1]])]
    if name == "TOTAL" and n == 1:
        return [_w("COALESCE"), Group([_w("SUM"), Group(args[0]), _op(","), Tok("number", "0.0")])]
    if name in ("DATETIME", "DATE", "TIME"):
        fmt = {"DATETIME": "YYYY-MM-DD HH24:MI:SS", "DATE": "YYYY-MM-DD", "TIME": "HH24:MI:SS"}[name]
        return [_raw(f"to_char({_time_value(args if n else [])}, '{fmt}')")]
    if name == "STRFTIME" and n >= 1:
        fmt = args[0]
        if len(fmt) != 1 or fmt[0].kind != "string":
            raise ValueError("strftime needs a text format")
        f = fmt[0].text[1:-1]
        if f == "%s":
            return [_raw(f"extract(epoch from {_time_value(args[1:])})::bigint")]
        pg = re.sub(r"%.", lambda m: _STRFTIME.get(m.group(), "\x00"), f)
        if "\x00" in pg:
            raise ValueError(f"the strftime format {f!r} is not translated for PostgreSQL")
        return [_raw(f"to_char({_time_value(args[1:])}, '{pg}')")]
    if name == "JULIANDAY":
        return [_raw(f"(extract(epoch from {_time_value(args)}) / 86400.0 + 2440587.5)")]
    if name == "UNIXEPOCH":
        return [_raw(f"extract(epoch from {_time_value(args)})::bigint")]
    if name == "CAST" and n == 1:
        a = list(args[0])
        k = max((i for i, t in enumerate(a) if _is(t, "AS")), default=-1)
        if k >= 0:
            return [_w("CAST"), Group([*a[:k + 1], *_sqlite_type(a[k + 1:])])]
    return None


_SQLITE_MASTER = (
    "(SELECT 'table'::text AS type, tablename::text AS name, tablename::text AS tbl_name, 0 AS rootpage, "
    "NULL::text AS sql FROM pg_tables WHERE schemaname = current_schema() UNION ALL "
    "SELECT 'index', indexname::text, tablename::text, 0, indexdef FROM pg_indexes WHERE schemaname = current_schema() "
    "UNION ALL SELECT 'view', viewname::text, viewname::text, 0, NULL FROM pg_views WHERE schemaname = current_schema())")
_ALIAS_STOP = {"WHERE", "ORDER", "GROUP", "LIMIT", "JOIN", "LEFT", "INNER", "CROSS", "ON", "UNION", "HAVING", "WINDOW",
               "OFFSET", "RIGHT", "FULL", "NATURAL", "USING", "EXCEPT", "INTERSECT"}


_NOT_A_CALL_AFTER = {"INTO", "TABLE", "EXISTS", "ON", "REFERENCES", "UPDATE", "FROM", "JOIN", "INDEX", "VIEW"}
_TYPE_WORDS = {"INTEGER", "INT", "BIGINT", "TEXT", "REAL", "BLOB", "NUMERIC", "VARCHAR", "BOOLEAN", "DOUBLE"}


def _level(items: Group) -> Group:
    """Apply the expression rules to one bracket level (and, recursively, to the levels inside it)."""
    return _pass_order_and_like([(_level(it) if isinstance(it, Group) else it) for it in items])


def _pass_order_and_like(src: list) -> Group:
    src = _pass_tokens(src)
    out: list = []
    i = 0
    while i < len(src):
        it = src[i]
        if _is(it, "ILIKE"):
            # the pattern's first operand gets the default collation: LIKE needs a deterministic one, and
            # columns declared COLLATE NOCASE use a non-deterministic (case-insensitive) collation
            if len(out) >= 2 and _is(out[-1], "NOCASE") and _is(out[-2], "COLLATE"):
                del out[-2:]
            j = i + 1
            span = 1
            if j + 1 < len(src) and isinstance(src[j], Tok) and src[j].kind == "word" and isinstance(src[j + 1], Group):
                span = 2
            while j + span + 1 < len(src) and _is_op(src[j + span], ".") and isinstance(src[j + span + 1], Tok):
                span += 2
            out += [it, *src[j:j + span], _raw('COLLATE "default"')]
            i = j + span
            continue
        if _is(it, "ORDER") and i + 1 < len(src) and _is(src[i + 1], "BY"):
            j = i + 2
            while j < len(src) and not _is(src[j], *_CLAUSE_END):
                j += 1
            terms = _split_commas(src[i + 2:j])
            out += [it, src[i + 1], *_join_commas([_nulls_like_sqlite(t) for t in terms])]
            i = j
            continue
        out.append(it)
        i += 1
    return Group(out)


def _pass_tokens(src: list) -> list:
    out: list = []
    i = 0
    while i < len(src):
        it = src[i]
        nxt = src[i + 1] if i + 1 < len(src) else None
        prev = out[-1] if out else None
        if isinstance(it, Tok) and it.kind == "word" and isinstance(nxt, Group) and not _is_op(prev, ".") \
                and not _is(prev, *_NOT_A_CALL_AFTER):
            new = _function(it.up, _split_commas(list(nxt)), nxt)
            if new is not None:
                out.extend(new)
                i += 2
                continue
            out.append(it)
        elif _is(it, "LIKE"):
            out.append(_w("ILIKE"))
        elif _is_op(it, "=="):
            out.append(_op("="))
        elif _is(it, "TRUE", "FALSE") and not _is(prev, "IS") and not (_is(prev, "NOT") and len(out) > 1
                                                                       and _is(out[-2], "IS")):
            out.append(Tok("number", "1" if it.up == "TRUE" else "0"))
        elif _is(it, "CURRENT_TIMESTAMP", "CURRENT_DATE", "CURRENT_TIME"):
            out.append(_raw(f"({_now_expr(it.up)})"))
        elif _is(it, "COLLATE") and nxt is not None:
            out += [it, _collation(nxt)]
            i += 2
            continue
        elif _is(it, "SQLITE_MASTER", "SQLITE_SCHEMA", "SQLITE_TEMP_MASTER") and not _is_op(prev, "."):
            out.append(_raw(_SQLITE_MASTER))
            if nxt is None or not (isinstance(nxt, Tok) and nxt.kind in ("word", "qident")) or _is(nxt, *_ALIAS_STOP):
                out.append(_raw("AS sqlite_master"))
        elif _is(it, "AS") and isinstance(nxt, Tok) and nxt.kind == "word" and nxt.up not in _TYPE_WORDS \
                and nxt.text != nxt.text.lower() and nxt.text != nxt.text.upper():
            out += [it, Tok("qident", _quote(nxt.text))]       # keep the alias's case, as SQLite does
            i += 2
            continue
        elif _is(it, "LIMIT"):
            # LIMIT -1 -> LIMIT ALL;  LIMIT offset, count -> LIMIT count OFFSET offset
            if _is_op(nxt, "-") and i + 2 < len(src) and isinstance(src[i + 2], Tok) and src[i + 2].text == "1":
                out += [it, _w("ALL")]
                i += 3
                continue
            if i + 3 < len(src) and _is_op(src[i + 2], ",") and not isinstance(src[i + 1], Group):
                out += [it, src[i + 3], _w("OFFSET"), src[i + 1]]
                i += 4
                continue
            out.append(it)
        else:
            out.append(it)
        i += 1
    return out


def _nulls_like_sqlite(term: list) -> list:
    """SQLite sorts NULLs first (ascending) and last (descending); PostgreSQL the other way round."""
    if not term or any(_is(t, "NULLS") for t in term):
        return term
    core = term[:-1] if _is(term[-1], "ASC", "DESC") else term
    if len(core) == 1 and _is(core[0], "ID", "ROWID") or (len(core) == 3 and _is_op(core[1], ".")
                                                         and _is(core[2], "ID", "ROWID")):
        return term                  # identity keys are never NULL; keep index scans for ORDER BY id
    return [*term, _w("NULLS"), _w("LAST" if _is(term[-1], "DESC") else "FIRST")]


