class Row(tuple):
    """A result row readable by position or column name, like sqlite3.Row."""
    __slots__ = ()
    _index: dict = {}
    _names: tuple = ()

    def __getitem__(self, key):
        if isinstance(key, str):
            i = self._index.get(key)
            if i is None:
                i = self._index.get(key.lower())
                if i is None:
                    raise IndexError("No item with that key")
            return tuple.__getitem__(self, i)
        return tuple.__getitem__(self, key)

    def keys(self) -> list[str]:
        return list(self._names)


@functools.lru_cache(maxsize=1024)
def _row_class(names: tuple) -> type:
    index: dict = {}
    for i, n in enumerate(names):
        index.setdefault(n, i)
        index.setdefault(n.lower(), i)
    return type("Row", (Row,), {"__slots__": (), "_index": index, "_names": names})


def _row_factory(cursor):
    res = cursor.pgresult              # names straight from the result: cheaper than cursor.description
    if res is None or not res.nfields:
        return tuple
    raw = [res.fname(i) for i in range(res.nfields)]
    if None in raw:                    # e.g. a server-side cursor: ask psycopg
        desc = cursor.description
        return _row_class(tuple(d.name for d in desc)) if desc else tuple
    enc = cursor.connection.info.encoding
    return _row_class(tuple(n.decode(enc) for n in raw))


class Cursor:
    """The part of sqlite3.Cursor Kosha uses."""

    def __init__(self, raw=None, rows: list | None = None, lastrowid: int | None = None, rowcount: int = -1):
        self._raw = raw
        self._rows = rows
        self.lastrowid = lastrowid
        self.rowcount = rowcount if raw is None else raw.rowcount
        res = raw.pgresult if raw is not None and rows is None else None
        self._has_rows = bool(res is not None and res.nfields)

    @property
    def description(self):
        return self._raw.description if self._has_rows else None

    def fetchone(self):
        if self._rows is not None:
            return self._rows.pop(0) if self._rows else None
        return self._raw.fetchone() if self._has_rows else None

    def fetchall(self) -> list:
        if self._rows is not None:
            rows, self._rows = self._rows, []
            return rows
        return self._raw.fetchall() if self._has_rows else []

    def fetchmany(self, size: int = 100) -> list:
        if self._rows is not None:
            rows, self._rows = self._rows[:size], self._rows[size:]
            return rows
        return self._raw.fetchmany(size) if self._has_rows else []

    def __iter__(self):
        return iter(self.fetchall())

    def close(self) -> None:
        if self._raw is not None:
            self._raw.close()


WRITE_LOCK_KEY = 0x4B6F736861      # "Kosha": one advisory lock per database serialises writers like SQLite
BUSY_TIMEOUT = "30s"                 # SQLite's busy_timeout in Kosha
_schema_cache: dict = {}
_schema_lock = threading.Lock()


class TransactionAborted(sqlite3.OperationalError):
    pass


def _import_psycopg():
    try:
        import psycopg
    except ImportError as e:      # pragma: no cover - depends on the installation
        raise RuntimeError('KOSHA_DATABASE_URL points at PostgreSQL, but the PostgreSQL driver is not installed. '
                           'Install it with:  pip install "psycopg[binary]"') from e
    return psycopg


def _as_sqlite_error(e: Exception) -> Exception:
    """psycopg error -> the matching sqlite3 exception (original kept as __cause__ and .pgcode)."""
    psycopg = _import_psycopg()
    cls = sqlite3.DatabaseError
    if isinstance(e, psycopg.IntegrityError):
        cls = sqlite3.IntegrityError
    elif isinstance(e, psycopg.DataError):
        cls = sqlite3.DataError
    elif isinstance(e, (psycopg.OperationalError, psycopg.ProgrammingError, psycopg.InternalError)):
        cls = sqlite3.OperationalError
    elif isinstance(e, psycopg.NotSupportedError):
        cls = sqlite3.NotSupportedError
    err = cls(str(e).strip())
    err.pgcode = getattr(e, "sqlstate", None)
    return err


def redact(url: str) -> str:
    """The URL without its password, for messages."""
    try:
        p = urlsplit(url)
        if p.password:
            host = p.hostname or ""
            netloc = f"{p.username}:***@{host}" + (f":{p.port}" if p.port else "")
            return urlunsplit((p.scheme, netloc, p.path, p.query, p.fragment))
    except ValueError:
        return "postgresql://***"
    return url


class _Loaders:
    """psycopg loaders that make results look like SQLite's (built once, when psycopg is first used)."""
    numeric = boolean = None

    @classmethod
    def get(cls):
        if cls.numeric is None:
            from psycopg.adapt import Loader

            class NumericLoader(Loader):          # SUM/AVG/ROUND come back as int or float, as in SQLite
                def load(self, data):
                    s = bytes(data).decode()
                    return float(s) if any(c in s for c in ".eEIN") else int(s)

            class BoolLoader(Loader):             # booleans are integers, as in SQLite
                def load(self, data):
                    return 1 if bytes(data) == b"t" else 0

            cls.numeric, cls.boolean = NumericLoader, BoolLoader
        return cls.numeric, cls.boolean


class Connection:
    """A PostgreSQL connection that Kosha's code can use as if it were a sqlite3 connection."""
    dialect = "postgresql"

    def __init__(self, url: str, application_name: str = "kosha"):
        self._psycopg = _import_psycopg()
        self._url, self._application_name = url, application_name
        self._last_id: int | None = None
        self.raw = self._open()

    def _open(self):
        psycopg = self._psycopg
        try:
            raw = psycopg.connect(self._url, autocommit=True, application_name=self._application_name,
                                  connect_timeout=15, prepare_threshold=None)
        except psycopg.Error as e:
            raise sqlite3.OperationalError(f"Could not connect to PostgreSQL at {redact(self._url)}: "
                                           f"{str(e).strip()}") from e
        numeric, boolean = _Loaders.get()
        raw.adapters.register_loader("numeric", numeric)
        raw.adapters.register_loader("bool", boolean)
        raw.row_factory = _row_factory
        # durability as with SQLite's synchronous=FULL; times in UTC; wait for the write lock like busy_timeout;
        # a transaction left idle for an hour (a stuck thread) is ended so it cannot hold the write lock forever
        raw.execute(f"SET synchronous_commit = on; SET TIME ZONE 'UTC'; SET lock_timeout = '{BUSY_TIMEOUT}'; "
                    "SET idle_in_transaction_session_timeout = '1h'")
        return raw

    def _reopen(self) -> None:
        """A new session after the old one was lost (PostgreSQL restarted, network dropped)."""
        try:
            self.raw.close()
        except Exception:
            pass
        self.raw = self._open()

    # -- state
    @property
    def broken(self) -> bool:
        return self.raw.closed or self.raw.broken

    @property
    def in_transaction(self) -> bool:
        s = self._psycopg.pq.TransactionStatus
        return self.raw.info.transaction_status in (s.INTRANS, s.INERROR, s.ACTIVE)

    @property
    def _aborted(self) -> bool:
        return self.raw.info.transaction_status == self._psycopg.pq.TransactionStatus.INERROR

    # -- transactions
    def _begin(self, retry: bool = True) -> None:
        if self.in_transaction:
            raise sqlite3.OperationalError("cannot start a transaction within a transaction")
        try:
            if self.broken:
                self._reopen()
            self.raw.execute(f"BEGIN; SELECT pg_advisory_xact_lock({WRITE_LOCK_KEY})")
        except self._psycopg.Error as e:
            if retry and self.broken:          # nothing had started: safe to try once more on a new session
                self._reopen()
                return self._begin(retry=False)
            self._rollback_quietly()
            if getattr(e, "sqlstate", "") == "55P03":
                raise sqlite3.OperationalError("database is locked: another change took longer than "
                                               f"{BUSY_TIMEOUT}; nothing was changed, try again") from e
            raise _as_sqlite_error(e) from e

    def _commit(self) -> None:
        if not self.in_transaction:
            return
        if self._aborted:
            self._rollback_quietly()
            raise TransactionAborted("A step of this change failed, so PostgreSQL undid the whole change; "
                                     "nothing was saved.")
        try:
            self.raw.execute("COMMIT")
        except self._psycopg.Error as e:
            self._rollback_quietly()
            raise _as_sqlite_error(e) from e

    def _rollback_quietly(self) -> None:
        try:
            if not self.raw.closed and self.in_transaction:
                self.raw.execute("ROLLBACK")
        except Exception:
            try:
                self.raw.close()        # a connection that cannot roll back is closed, so nothing stays open
            except Exception:
                pass

    def commit(self) -> None:
        self._commit()

    def rollback(self) -> None:
        if self.in_transaction:
            try:
                self.raw.execute("ROLLBACK")
            except self._psycopg.Error as e:
                raise _as_sqlite_error(e) from e

    def close(self) -> None:
        self._rollback_quietly()
        self.raw.close()

    # -- statements
    def execute(self, sql: str, params: Sequence | dict = ()) -> Cursor:
        try:
            t = translate(sql)
        except ValueError as e:
            raise sqlite3.OperationalError(f"{e}: {sql.strip()[:200]}") from None
        if t.action == "begin":
            self._begin()
            return Cursor()
        if t.action == "commit":
            self._commit()
            return Cursor()
        if t.action == "rollback":
            self.rollback()
            return Cursor()
        if t.action == "noop":
            return Cursor(rows=[])
        if isinstance(params, dict):
            args: Any = {k: (int(v) if isinstance(v, bool) else v) for k, v in params.items()}
        else:
            args = tuple(int(v) if isinstance(v, bool) else v for v in params)
        if not t.write:
            return self._run(t.sql, args)
        if self.in_transaction:
            return self._write(t, args, savepoint=True)
        self._begin()
        try:
            cur = self._write(t, args, savepoint=False)
        except BaseException:
            self._rollback_quietly()
            raise
        self._commit()
        return cur

    def _run(self, sql: str, args) -> Cursor:
        in_tx = self.in_transaction
        try:
            if self.broken and not in_tx:
                self._reopen()
            return Cursor(self.raw.execute(sql, args))
        except self._psycopg.Error as e:
            if not in_tx and self.broken:      # a read outside a transaction: run it again on a new session
                try:
                    self._reopen()
                    return Cursor(self.raw.execute(sql, args))
                except self._psycopg.Error as e2:
                    raise _as_sqlite_error(e2) from e2
            raise _as_sqlite_error(e) from e

    def _write(self, t: Translated, args, savepoint: bool) -> Cursor:
        try:
            sql = t.sql
            if t.upsert:
                sql = sql.replace(UPSERT_MARK, self._upsert_clause(t))
            id_col = ""
            if t.insert_table and not t.returning:
                id_col = self._identity(t.insert_table)
                if id_col:
                    sql += f" RETURNING {_quote(id_col)}"
        except self._psycopg.Error as e:
            raise _as_sqlite_error(e) from e
        started = False
        try:
            if savepoint:
                self.raw.execute("SAVEPOINT kosha_statement")
                started = True
            raw = self.raw.execute(sql, args)
            cur = Cursor(raw)
            if id_col:
                ids = raw.fetchall()
                if ids:
                    self._last_id = ids[-1][0]
                cur = Cursor(rows=[], lastrowid=self._last_id, rowcount=raw.rowcount)
                if id_col in t.insert_columns:     # an explicit id: move the sequence past it
                    self.raw.execute("SELECT setval(pg_get_serial_sequence(%s, %s), GREATEST((SELECT MAX({c}) FROM {tb}),"
                                     " 1))".format(c=_quote(id_col), tb=_quote(t.insert_table)),
                                     (_quote(t.insert_table), id_col))
            else:
                cur.lastrowid = self._last_id
            if savepoint:
                self.raw.execute("RELEASE SAVEPOINT kosha_statement")
        except self._psycopg.Error as e:
            if started and self._aborted:
                try:
                    self.raw.execute("ROLLBACK TO SAVEPOINT kosha_statement; RELEASE SAVEPOINT kosha_statement")
                except self._psycopg.Error:
                    pass
            raise _as_sqlite_error(e) from e
        if t.ddl:
            with _schema_lock:
                _schema_cache.clear()
        return cur

    def executemany(self, sql: str, seq_of_params: Iterable) -> Cursor:
        cur = Cursor(rows=[])
        n = 0
        for p in seq_of_params:
            cur = self.execute(sql, p)
            n += max(cur.rowcount, 0)
        cur.rowcount = n
        return cur

    def executescript(self, script: str) -> Cursor:
        for stmt in split_statements(script):
            self.execute(stmt)
        return Cursor(rows=[])

    def execute_native(self, script: str) -> None:
        """Run PostgreSQL SQL as it is (no translation, no place holders), e.g. a migration's SQL_POSTGRESQL."""
        if not script.strip():
            return
        try:
            self.raw.execute(script)
        except self._psycopg.Error as e:
            raise _as_sqlite_error(e) from e
        finally:
            with _schema_lock:
                _schema_cache.clear()

    # -- what the translator needs to know about tables
    def _catalog(self, key: tuple, sql: str, args: tuple):
        with _schema_lock:
            if key in _schema_cache:
                return _schema_cache[key]
        rows = [tuple(r) for r in self.raw.execute(sql, args).fetchall()]
        with _schema_lock:
            _schema_cache[key] = rows
        return rows

    def _identity(self, table: str) -> str:
        rows = self._catalog(("identity", table),
                             "SELECT a.attname FROM pg_attribute a WHERE a.attrelid = to_regclass(%s) AND a.attnum > 0 "
                             "AND NOT a.attisdropped AND (a.attidentity <> '' OR pg_get_serial_sequence(%s, a.attname) "
                             "IS NOT NULL) ORDER BY a.attnum LIMIT 1", (_quote(table), _quote(table)))
        return rows[0][0] if rows else ""

    def _upsert_clause(self, t: Translated) -> str:
        table = _quote(t.insert_table)
        keys = self._catalog(("unique", t.insert_table),
                             "SELECT ARRAY(SELECT a.attname::text FROM unnest(i.indkey::int2[]) WITH ORDINALITY k(n, o) "
                             "JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = k.n ORDER BY k.o) "
                             "FROM pg_index i WHERE i.indrelid = to_regclass(%s) AND i.indisunique "
                             "AND i.indpred IS NULL AND i.indexprs IS NULL ORDER BY i.indisprimary DESC, i.indexrelid",
                             (table,))
        cols = self._catalog(("columns", t.insert_table),
                             "SELECT attname::text, attidentity <> '' OR attgenerated <> '' FROM pg_attribute "
                             "WHERE attrelid = to_regclass(%s) AND attnum > 0 AND NOT attisdropped ORDER BY attnum",
                             (table,))
        inserted = set(t.insert_columns) or {c for c, _auto in cols}
        target = next((k[0] for k in keys if set(k[0]) <= inserted), None)
        if target is None:
            raise sqlite3.OperationalError(f"INSERT OR REPLACE into {t.insert_table} needs a unique key among the "
                                           "inserted columns")
        sets = [f"{_quote(c)} = EXCLUDED.{_quote(c)}" for c in t.insert_columns if c not in target]
        sets += [f"{_quote(c)} = DEFAULT" for c, auto in cols if c not in inserted and c not in target and not auto]
        conflict = "ON CONFLICT (" + ", ".join(_quote(c) for c in target) + ")"
        return f" {conflict} DO UPDATE SET {', '.join(sets)}" if sets else f" {conflict} DO NOTHING"


def connect(url: str, application_name: str = "kosha") -> Connection:
    return Connection(url, application_name)


def prepare_database(conn) -> None:
    """What the translation needs in a new database: the case-insensitive collation behind COLLATE NOCASE."""
    try:
        conn.raw.execute(f"BEGIN; SELECT pg_advisory_xact_lock({WRITE_LOCK_KEY})")
        conn.raw.execute("CREATE COLLATION IF NOT EXISTS nocase (provider = icu, locale = 'und-u-ks-level2', "
                         "deterministic = false)")
        conn.raw.execute("COMMIT")
    except conn._psycopg.Error as e:
        conn._rollback_quietly()
        raise sqlite3.OperationalError(
            "Kosha could not create its case-insensitive collation in PostgreSQL. Kosha needs PostgreSQL 12 or "
            "newer built with ICU (all standard packages are), and its database user must own the database. "
            f"PostgreSQL said: {str(e).strip()}") from e
