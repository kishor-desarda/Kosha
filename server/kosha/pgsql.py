"""PostgreSQL support: Kosha's SQLite-flavoured SQL translated for PostgreSQL.

Kosha's modules (and every database change in ``migrations/``) write SQL the SQLite way: ``?`` place
holders, ``COLLATE NOCASE``, ``IFNULL``, ``INSERT OR IGNORE``, ``INTEGER PRIMARY KEY`` ... When
``KOSHA_DATABASE_URL`` points at PostgreSQL, :func:`connect` returns a connection that behaves like
``sqlite3``'s (rows readable by column name, ``lastrowid``, ``BEGIN IMMEDIATE``, ``executescript``)
and runs every statement through :func:`translate` first. All translation rules live in this file,
each with a unit test in ``tests/test_pgsql.py``:

=========================================  ==========================================================
SQLite                                     PostgreSQL
=========================================  ==========================================================
``?`` and ``:name`` place holders          ``%s`` and ``%(name)s`` (a literal ``%`` becomes ``%%``)
``COLLATE NOCASE``                         ``COLLATE nocase``, an ICU case-insensitive collation that
                                           :func:`prepare_database` creates; it works in comparisons,
                                           ORDER BY, unique constraints and indexes. In column
                                           definitions it moves next to the type.
``x LIKE p``                               ``x ILIKE p COLLATE "default"`` (case-insensitive like
                                           SQLite, and allowed on case-insensitive columns)
``IFNULL`` ``IIF`` ``INSTR``               ``COALESCE``, ``CASE``, ``strpos``
``last_insert_rowid()``                    ``lastval()``
``GROUP_CONCAT(x[, sep])``                 ``string_agg((x)::text, sep)``
``MAX(a, b)`` ``MIN(a, b)``                ``GREATEST`` ``LEAST``
``ROUND(x, n)``                            ``ROUND((x)::numeric, n)``
``REPLACE(x, a, b)``                       works on case-insensitive columns too
``datetime/date/time/strftime/julianday``  ``to_char`` / ``extract`` on UTC time; ``'now'``, columns
``CURRENT_TIMESTAMP`` ...                  and ``'+N days'``-style modifiers
``TRUE`` ``FALSE`` ``==``                  ``1`` ``0`` ``=`` (booleans are stored as integers)
``INSERT OR IGNORE``                       ``INSERT ... ON CONFLICT DO NOTHING``
``INSERT OR REPLACE`` / ``REPLACE INTO``   ``INSERT ... ON CONFLICT (unique key) DO UPDATE``; the key is
                                           read from the table (unset columns go back to defaults)
``INTEGER PRIMARY KEY [AUTOINCREMENT]``    ``BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY``
column types                               ``INTEGER`` → ``BIGINT``, ``REAL`` → ``DOUBLE PRECISION``,
                                           ``BLOB`` → ``BYTEA``, dates and ``BOOLEAN`` keep SQLite's
                                           storage (text, integer)
``ORDER BY x [DESC]``                      ``... NULLS FIRST`` (``NULLS LAST`` for DESC), as SQLite sorts
``LIMIT a, b`` / ``LIMIT -1``              ``LIMIT b OFFSET a`` / ``LIMIT ALL``
``AS camelCase``                           ``AS "camelCase"`` (keeps the name SQLite returns)
``PRAGMA table_info/index_list``           catalogue queries with SQLite's column names
other ``PRAGMA``\\s, ``VACUUM``            nothing (PostgreSQL manages these itself)
``sqlite_master`` / ``sqlite_schema``      a view over ``pg_tables`` and ``pg_indexes``
``BEGIN [IMMEDIATE]`` ``COMMIT`` ``END``   transaction control, see below
=========================================  ==========================================================

Transactions behave like SQLite's ``BEGIN IMMEDIATE``: a write transaction first takes one
database-wide advisory lock, so writers run one at a time (and wait up to 30 seconds, like SQLite's
busy time-out) while readers carry on. Single writing statements outside a transaction take the
same lock. Inside a transaction every writing statement runs under a savepoint, so a failed
statement is undone on its own and the transaction can carry on, as in SQLite. A transaction
that PostgreSQL has already aborted is never reported as committed. A session lost outside a
transaction (PostgreSQL restarted) is replaced and the statement runs again; inside a transaction
the change fails as a whole and nothing of it is saved. ``INSERT`` returns the new
row's id (``RETURNING``) for ``lastrowid``; database errors are raised as the matching ``sqlite3``
exceptions so ``except sqlite3.IntegrityError`` works on both engines.

Not translated (write it differently, or give a migration ``SQL_POSTGRESQL``): triggers, virtual
tables (FTS), ``GLOB``, ``?NNN`` place holders. PostgreSQL is also stricter than SQLite, so write SQL
that both accept (the CI job ``postgres`` runs every test on PostgreSQL):

- conditions are comparisons (``WHERE active = 1``, not ``WHERE active``); no ``SUM(a = b)``;
- every selected column is grouped or aggregated; ``SELECT DISTINCT`` orders only by selected columns;
- compare text with text and numbers with numbers (``WHERE code = ?`` with a ``str``);
- text in single quotes (``'item'``, never ``"item"``); no reserved words as names (``user``, ``order``);
- ``INSERT OR REPLACE`` keeps the row's id (SQLite gives a new one); text sorts by the database's collation
  (``C.UTF-8`` gives SQLite's order); ``sqlite_master.sql`` is empty for tables: use ``PRAGMA table_info``.
"""
